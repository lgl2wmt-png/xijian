for (const code of langs) {
  const path = join(root, `${code}.json`)
  const cur = JSON.parse(readFileSync(path, 'utf8'))
  let add = pages[code] || packs[code] || more[code]
  if (!add) add = {}
  // Always ensure galaxy/sandbox/hud from EN if missing
  const enUi = pages.en
  const mergedAdd = {
    ...enUi,
    ...add,
    galaxyUi: add.galaxyUi || enUi.galaxyUi,
    sandboxUi: add.sandboxUi || enUi.sandboxUi,
    hudUi: add.hudUi || enUi.hudUi,
    catalog: add.catalog || enUi.catalog,
  }
  // For zh use pages.zh fully
  const patch = code === 'zh' ? pages.zh : code === 'en' ? pages.en : mergedAdd
  const next = deepMerge(cur, patch)
  // Flatten commonExtra into common
  if (next.commonExtra) {
    next.common = { ...next.common, ...next.commonExtra }
    delete next.commonExtra
  }
  writeFileSync(path, JSON.stringify(next, null, 2) + '\n', 'utf8')
  console.log('merged', code)
}
