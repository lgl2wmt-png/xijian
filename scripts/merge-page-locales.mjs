function deepMerge(a, b) {
  const out = { ...a }
  for (const [k, v] of Object.entries(b || {})) {
    if (v && typeof v === 'object' && !Array.isArray(v) && a[k] && typeof a[k] === 'object') {
      out[k] = deepMerge(a[k], v)
    } else if (v != null) {
      out[k] = v
    }
  }
  return out
}

// For langs without full copy, clone EN then overlay available
function buildLang(code) {
  if (pages[code]) return pages[code]
  const base = structuredClone(pages.en)
  if (more[code]) {
    for (const [k, v] of Object.entries(more[code])) {
      if (v == null) continue
      base[k] = v
    }
  }
  return base
}

